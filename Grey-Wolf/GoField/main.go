// ============================================================
// 知识点 1：包声明（Package Declaration）
// 每个 Go 文件的第一行必须声明它属于哪个包。
// "main" 包是特殊的——它代表一个可独立执行的程序入口。
// ============================================================
package main

// ============================================================
// 知识点 2：引入包（Import Packages）
// 使用 import 引入标准库或第三方包。
// "fmt" 包提供格式化输入/输出功能。
// 引入多个包时推荐使用括号形式（分组导入）。
// ============================================================
import (
	"fmt"  // 格式化 I/O
	"math" // 数学函数
)

// ============================================================
// 知识点 3：标识符可见性（Exported vs Unexported）
// 以大写字母开头 → 对外可见（public），其他包可以使用
// 以小写字母开头 → 仅包内可见（package-private）
// ============================================================
const PublicConstant = "我是公开常量，其他包可以访问我"  // 导出
const privateConstant = "我是私有常量，只有本包能访问我" // 未导出

// ============================================================
// 知识点 4：函数（Function）
// 使用 func 关键字定义函数。
// main() 是程序的入口函数，每个可执行程序必须有且只有一个。
// ============================================================

// greet 是一个自定义函数（小写开头 = 包内可见）
// 参数：name string；返回值：string
func greet(name string) string {
	return "你好，" + name + "！"
}

// add 演示多参数、单返回值函数
func add(a int, b int) int {
	return a + b
}

// ============================================================
// 知识点 5：变量（Variables）
// Go 变量必须先声明再使用，有三种常用声明方式：
//   var name type         → 标准声明（零值初始化）
//   var name type = value → 声明并赋值
//   name := value         → 短变量声明（自动推断类型，仅限函数内）
// ============================================================

// 包级变量（函数外声明，不能用 :=）
var globalVar = "我是全局变量"

func main() {
	// --------------------------------------------------------
	// 知识点 4 演示：调用函数
	// --------------------------------------------------------
	fmt.Println("=== 知识点 4：函数 ===")
	message := greet("Go学习者")
	fmt.Println(message)
	fmt.Println("3 + 5 =", add(3, 5))

	// --------------------------------------------------------
	// 知识点 5 演示：变量
	// --------------------------------------------------------
	fmt.Println("\n=== 知识点 5：变量 ===")

	// 方式1：var 声明，零值初始化（int 零值为 0，string 零值为 ""）
	var age int
	var city string
	fmt.Printf("零值 → age: %d, city: \"%s\"\n", age, city)

	// 方式2：var 声明并赋值
	var score int = 100
	fmt.Println("score:", score)

	// 方式3：短变量声明（:= 自动推断类型）
	name := "张三"
	height := 1.75
	fmt.Printf("name: %s, height: %.2f\n", name, height)

	// 全局变量
	fmt.Println("全局变量:", globalVar)

	// --------------------------------------------------------
	// 知识点 6：语句 & 表达式（Statements & Expressions）
	// 语句：执行动作（赋值、函数调用、控制流等）
	// 表达式：计算并产生一个值
	// --------------------------------------------------------
	fmt.Println("\n=== 知识点 6：语句 & 表达式 ===")

	// 赋值语句
	x := 10
	y := 3

	// 算术表达式
	sum := x + y
	product := x * y
	remainder := x % y
	fmt.Printf("%d + %d = %d\n", x, y, sum)
	fmt.Printf("%d * %d = %d\n", x, y, product)
	fmt.Printf("%d %% %d = %d\n", x, y, remainder)

	// 调用标准库 math 中的函数（表达式）
	hypotenuse := math.Sqrt(float64(x*x + y*y))
	fmt.Printf("斜边长度(勾股定理): %.4f\n", hypotenuse)

	// --------------------------------------------------------
	// 知识点 7：注释（Comments）
	// --------------------------------------------------------
	fmt.Println("\n=== 知识点 7：注释 ===")

	// 这是单行注释，以 // 开头，常用于解释单行代码

	/*
	   这是多行注释（块注释），以 /* 开头、以 * / 结尾。
	   常用于：
	     - 包的文档描述
	     - 注释掉一大块代码
	     - 编写多行说明
	*/

	fmt.Println("注释不会被执行，只是给人类读的说明文字")

	// --------------------------------------------------------
	// 知识点 3 演示：标识符可见性
	// --------------------------------------------------------
	fmt.Println("\n=== 知识点 3：标识符可见性 ===")
	fmt.Println(PublicConstant)
	fmt.Println(privateConstant) // 在本包内可以访问

	// fmt.Println 中的 Println 以大写开头 → 这就是"导出"的体现
	// 如果是小写的 println，则是 Go 内置函数，不来自 fmt 包

	// --------------------------------------------------------
	// 知识点 8：{ 必须与函数声明在同一行
	// 以下写法会编译报错（已注释掉，仅作说明）：
	//
	// func wrong()
	// {   ← 错误！{ 不能单独放在新行
	//     fmt.Println("编译报错")
	// }
	// --------------------------------------------------------
	fmt.Println("\n=== 知识点 8：{ 不能单独放在新行 ===")
	fmt.Println("Go 强制要求左花括号 { 必须和 func/if/for 等在同一行")

	// --------------------------------------------------------
	// 综合演示：fmt 常用输出函数
	// --------------------------------------------------------
	fmt.Println("\n=== 综合：fmt 输出函数对比 ===")
	fmt.Print("Print：不自动换行")
	fmt.Print("，继续在同一行\n")
	fmt.Println("Println：自动加换行")
	fmt.Printf("Printf：格式化输出，整数=%d 浮点=%.2f 字符串=%s\n", 42, 3.14, "Go")
}
